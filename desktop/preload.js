// 웹 앱에서 쓸 수 있는 데스크톱 기능(구글 로그인, 버전)
const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('nvDesktop', {
  version: () => ipcRenderer.invoke('version'),
  gdToken: (id, secret) => ipcRenderer.invoke('gd-token', id, secret),
  gdLogin: (id, secret, scope) => ipcRenderer.invoke('gd-login', id, secret, scope),
  libPick: () => ipcRenderer.invoke('lib-pick'),
  libScan: p => ipcRenderer.invoke('lib-scan', p),
  gdLogout: () => ipcRenderer.invoke('gd-logout'),
  gdSecret: s => ipcRenderer.invoke('gd-secret', s),   // 구글 보안 비밀번호: 이 PC에만 암호화해 둔다
  openFolder: () => ipcRenderer.invoke('open-data-folder'),
  naiGen: (token, body) => ipcRenderer.invoke('nai-gen', token, body),
  naiCapture: () => ipcRenderer.invoke('nai-capture'),
  libInfo: p => ipcRenderer.invoke('lib-info', p),
  libFind: p => ipcRenderer.invoke('lib-find', p),
  libRepick: p => ipcRenderer.invoke('lib-repick', p),
  odToken: (id, scope) => ipcRenderer.invoke('od-token', id, scope),
  odLogin: (id, scope) => ipcRenderer.invoke('od-login', id, scope),
  odLogout: () => ipcRenderer.invoke('od-logout'),
  lanInfo: () => ipcRenderer.invoke('lan-info'),
  lanSet: on => ipcRenderer.invoke('lan-set', on),
  trPageGet: key => ipcRenderer.invoke('tr-page-get', key),
  trPageHas: keys => ipcRenderer.invoke('tr-page-has', keys),
  pcSyncList: () => ipcRenderer.invoke('pcsync-list'),
  pcSyncGet: n => ipcRenderer.invoke('pcsync-get', n),
  pcSyncPut: (n, data) => ipcRenderer.invoke('pcsync-put', n, data),
  pcSyncDel: n => ipcRenderer.invoke('pcsync-del', n),
  onPcSyncChanged: cb => ipcRenderer.on('pcsync-changed', () => cb()),
  lanRemoteInfo: () => ipcRenderer.invoke('lan-remote-info'),
  lanRemoteSet: on => ipcRenderer.invoke('lan-remote-set', on),
  onLanRemote: cb => ipcRenderer.on('lan-remote', (_e, info) => cb(info)),
  libSibling: (of, name) => ipcRenderer.invoke('lib-sibling', of, name),
  libDlFolders: () => ipcRenderer.invoke('lib-dl-folders'),
  libDlLink: p => ipcRenderer.invoke('lib-dl-link', p),
  onLibDlNew: cb => ipcRenderer.on('lib-dl-new', () => cb()),
  ollamaStart: () => ipcRenderer.invoke('ollama-start'),
  onLibChanged: cb => ipcRenderer.on('lib-changed', (_e, root) => cb(root)),
  trStatus: () => ipcRenderer.invoke('tr-status'),
  trInstall: () => ipcRenderer.invoke('tr-install'),
  trStart: () => ipcRenderer.invoke('tr-start'),
  onTrInstallLog: cb => ipcRenderer.on('tr-install-log', (_e, line) => cb(line)),
});
